from __future__ import annotations

import locale
import os

_lang = "it"


def detect_language() -> str:
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var)
        if value:
            return "it" if value.lower().startswith("it") else "en"
    try:
        code = locale.getlocale()[0] or ""
    except ValueError:
        code = ""
    if not code:
        try:
            from PySide6.QtCore import QLocale

            code = QLocale.system().name()
        except ImportError:
            code = ""
    return "it" if code.lower().startswith("it") else "en"


def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in ("it", "en") else detect_language()


def language() -> str:
    return _lang


